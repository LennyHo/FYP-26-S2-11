export function createConversationId(): string {
  if (typeof crypto !== 'undefined' && typeof crypto.randomUUID === 'function') {
    return crypto.randomUUID();
  }
  return `${Date.now()}-${Math.random().toString(16).slice(2, 10)}`;
}

export function convertDrinkNamesToLinks(text: string): string {
  let result = text;

  // Replace drink names with links (bold or asterisk format from server)
  Object.entries(drinkData).forEach(([drinkName, { id, category }]) => {
    const url = `/menu/${category}/${id}`;
    
    // Handle **Drink Name** format
    const boldPattern = new RegExp(`\\*\\*${drinkName}\\*\\*`, 'g');
    result = result.replace(boldPattern, `<a href="${url}" class="chat-drink-link" style="color: #2b7da3; text-decoration: none; border-bottom: 2px solid #2b7da3; font-weight: bold;"><strong>${drinkName}</strong></a>`);
    
    // Handle ***Drink Name*** format
    const boldItalicPattern = new RegExp(`\\*\\*\\*${drinkName}\\*\\*\\*`, 'g');
    result = result.replace(boldItalicPattern, `<a href="${url}" class="chat-drink-link" style="color: #2b7da3; text-decoration: none; border-bottom: 2px solid #2b7da3; font-weight: bold;"><strong>${drinkName}</strong></a>`);
  });
  
  return result;
}

export function parseDrinkFromHtml(html: string) {
  try {
    const imageMatch = html.match(/<img[^>]+src=['"]([^'"]+)['"][^>]*>/i);
    const altMatch = html.match(/<img[^>]+alt=['"]([^'"]+)['"][^>]*>/i);
    const nameMatch =
      html.match(/\*\*([^*]+)\*\*\s*\(\$?([^)]+)\)/) ||
      html.match(/<strong>([^<]+)<\/strong>\s*\(\$?([^)]+)\)/i);
    const statsMatch = html.match(/Nutri\s*Grade:\s*([A-F])\s*\|\s*Sugar:\s*([^|<\n]+?)g?\s*\|\s*Calories:\s*([^<\n]+?)(?:\s*kcal)?(?:<|$)/i);
    const idMatch =
      html.match(/startOrder\((?:\\?["'])([^"')\\]+)(?:\\?["'])\)/i) ||
      html.match(/data-drink-id=['"]([^'"]+)['"]/i);

    if (!nameMatch || !statsMatch || !idMatch) {
      return null;
    }

    return {
      id: idMatch[1],
      name: nameMatch[1]?.trim() || altMatch?.[1]?.trim() || 'Recommended drink',
      image: imageMatch?.[1] || '/img/bubble_teas/test.jpg',
      price: nameMatch[2].trim(),
      grade: statsMatch[1].trim(),
      sugar: statsMatch[2].trim(),
      calories: statsMatch[3].trim(),
    };
  } catch (e) {
    return null;
  }
}

export function applyGlossaryTooltips(html: string): string {
  let result = html;
  GLOSSARY_TERMS.forEach(term => {
    const regex = new RegExp(`\\b${term}\\b`, 'gi');
    const replacement = `<span title="${GLOSSARY[term] || ''}">${term}</span>`;
    result = result.replace(regex, replacement);
  });
  return result;
}

// Ingredient keywords that open the detail modal in the chatbot
const INGREDIENT_KEYWORD_MAP: { pattern: string; key: string }[] = [
  // multi-word first (longest match wins)
  { pattern: 'tapioca starch', key: 'tapioca starch' },
  { pattern: 'tapioca pearls', key: 'pearl' },
  { pattern: 'tapioca pearl', key: 'pearl' },
  { pattern: 'cassava root', key: 'tapioca starch' },
  { pattern: 'boba pearl', key: 'pearl' },
  { pattern: 'cheese foam', key: 'cheese foam' },
  { pattern: 'cream cheese', key: 'cheese foam' },
  { pattern: 'aloe vera', key: 'aloe vera' },
  // single-word fallbacks
  { pattern: 'tapioca', key: 'tapioca starch' },
  { pattern: 'cassava', key: 'tapioca starch' },
  { pattern: 'boba', key: 'pearl' },
  { pattern: 'pearl', key: 'pearl' },
].sort((a, b) => b.pattern.length - a.pattern.length); // longest match first

export function applyIngredientKeywords(html: string): string {
  // Split into alternating text / tag segments; only process text segments (even indices)
  const segments = html.split(/(<[^>]*>)/g);
  return segments
    .map((seg, i) => (i % 2 === 0 ? _highlightKeywordsInText(seg) : seg))
    .join('');
}

function _highlightKeywordsInText(text: string): string {
  if (!text) return text;

  // Collect all non-overlapping matches across every pattern
  type Match = { start: number; end: number; key: string; match: string };
  const found: Match[] = [];

  INGREDIENT_KEYWORD_MAP.forEach(({ pattern, key }) => {
    const re = new RegExp(`(?<![a-zA-Z])(${pattern})(?![a-zA-Z])`, 'gi');
    let m: RegExpExecArray | null;
    while ((m = re.exec(text)) !== null) {
      found.push({ start: m.index, end: m.index + m[0].length, key, match: m[0] });
    }
  });

  if (found.length === 0) return text;

  // Sort: earlier position first; for ties, longer match wins
  found.sort((a, b) => a.start - b.start || (b.end - b.start) - (a.end - a.start));

  // Remove overlapping entries (greedy, keep first/longest)
  const kept: Match[] = [];
  let cursor = 0;
  for (const m of found) {
    if (m.start >= cursor) {
      kept.push(m);
      cursor = m.end;
    }
  }

  // Build result right-to-left so indices stay valid
  let result = text;
  for (let i = kept.length - 1; i >= 0; i--) {
    const { start, end, key, match } = kept[i];
    const span = `<span class="chat-keyword" data-keyword="${key}" style="border-bottom:2px dotted rgba(255,255,255,0.8);color:#ffffff;font-weight:700;cursor:pointer;white-space:nowrap;text-underline-offset:3px;">${match}</span>`;
    result = result.slice(0, start) + span + result.slice(end);
  }
  return result;
}
